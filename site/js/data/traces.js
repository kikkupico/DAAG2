// Global traces: the whole system's history for a scene, not one node's diary.
// A scene in site/js/data/scenes*.js is told from inside one node (`who`). Its trace says what every node holds at every
// step, and when each message leaves and arrives. Projected onto `who`, a trace must give back the scene's rows exactly:
// node site/tools/check-traces.js checks that, so the two never drift apart.
//
// Shape, keyed by the scene's key (`<paper>-<scene>`):
//   nodes: { X: { role, init: { perm, temp } } }        every participant, in the order the picker lists them
//   steps: [ { note, acts: { X: { perm, temp, why } } } ]  steps[0] is the start (a note only); step k is a moment of the
//          global clock. A node acts at step k if it has an entry there or a message leaves or reaches it there.
//          perm and temp are deltas, as in a scene's rows. `why` is the node's own one-line account, for nodes other
//          than `who` (whose account is the scene's prose). `isle`, where given, is the Allegory's own telling of it,
//          with the telling's {places}; elsewhere the Allegory shows `why` with its word swaps (TELL[paper].lex).
//   msgs:  [ [from, to, text, sent, arrives, flag] ]      `sent` and `arrives` are step numbers. from may be "outside", "timer",
//          "coin" (a coin tossed at the node) or "nothing" (an empty step: the node acts, and nothing has arrived), each
//          arriving at the step after `sent`; to may be "outside" (a reply to the client, which leaves the scene: arrives = sent).
//          arrives: null means still on its way when the scene ends. flag "lost": it vanishes at step `arrives` (or, with
//          arrives null, after the scene ends).
//          Within a step, a node's arrivals and departures keep the order of this list.
